/**
 * Bridge (by Stripe) - the single shared server-only API client.
 *
 * Every Bridge REST call in PineTree goes through `bridgeRequest`. It owns URL
 * selection, required headers, idempotency, timeouts, response parsing, error
 * classification, and redaction. No route, component, engine module, or
 * wrapper may call fetch against Bridge directly.
 *
 * ── Authentication ───────────────────────────────────────────────────────────
 * Bridge authenticates with the `Api-Key` request header. It is NOT a Stripe
 * secret key and NOT a bearer token, and it never appears in a log, an error,
 * a return value, or a database row.
 *
 * ── Idempotency ──────────────────────────────────────────────────────────────
 * Bridge requires `Idempotency-Key` on mutating requests. PineTree ALWAYS
 * generates the key itself, deterministically, from the merchant and the
 * onboarding version - never from a client-supplied value and never randomly.
 * That is what makes a retried onboarding reuse the same Bridge customer
 * instead of creating a second one.
 *
 * ── Retry policy ─────────────────────────────────────────────────────────────
 * This client performs no automatic retries. A timeout leaves the outcome
 * UNKNOWN: Bridge may already have created the object. Resolution belongs to
 * the Engine, which retries with the SAME idempotency key or re-reads state.
 */

