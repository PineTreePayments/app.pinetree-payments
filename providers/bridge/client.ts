export type CreateBridgeKycLinkInput = {
  /** For a business this is the full LEGAL business name, per Bridge's docs. */
  fullName: string
  email: string
  type: BridgeCustomerType
  /** Endorsements to request during onboarding, e.g. ["base"]. */
  endorsements?: string[]
  redirectUri?: string
  idempotencyKey: string
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}

/**
 * Create a hosted Bridge KYC/KYB link.
 *
 * PineTree uses Bridge's hosted flow rather than rebuilding KYB collection, so
 * documents and personal identifiers go from the merchant's browser to Bridge
 * and never transit or rest in PineTree.
 */
export async function createKycLink(
  input: CreateBridgeKycLinkInput
): Promise<BridgeRequestResult<BridgeKycLink>> {
  const body: Record<string, unknown> = {
    full_name: input.fullName,
    email: input.email,
    type: input.type,
  }
  if (input.endorsements?.length) body.endorsements = input.endorsements
  if (input.redirectUri) body.redirect_uri = input.redirectUri

  const result = await bridgeRequest<BridgeKycLink>({
    operation: "create_kyc_link",
    method: "POST",
    path: "/kyc_links",
    body,
    idempotencyKey: input.idempotencyKey,
    context: input.context,
    config: input.config,
    fetchImpl: input.fetchImpl,
  })

  assertIdentifiedObject(result.data, "create_kyc_link", {
    correlationId: result.correlationId,
    merchantId: input.context?.merchantId ?? null,
  })
  return result
}

export async function getKycLink(input: {
  kycLinkId: string
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}): Promise<BridgeRequestResult<BridgeKycLink>> {
  return bridgeRequest<BridgeKycLink>({
    operation: "get_kyc_link",
    method: "GET",
    path: `/kyc_links/${pathSegment(input.kycLinkId, "get_kyc_link")}`,
    context: input.context,
    config: input.config,
    fetchImpl: input.fetchImpl,
  })
}

