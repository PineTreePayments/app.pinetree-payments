/**
 * Read the merchant's current Bridge state from whichever identifiers exist.
 *
 * Returns the NORMALIZED connection; callers never see raw Bridge objects.
 * Both reads are attempted because the KYC link carries TOS acceptance while
 * the customer carries endorsements, and neither alone is sufficient.
 */
export async function syncCustomerStatus(input: {
  customerId?: string | null
  kycLinkId?: string | null
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}): Promise<{ connection: NormalizedBridgeConnection; correlationId: string }> {
  const correlationId = input.context?.correlationId || randomUUID()
  const context = { ...input.context, correlationId }

  const kycLinkId = String(input.kycLinkId || "").trim()
  const customerIdFromInput = String(input.customerId || "").trim()

  let kycLink: BridgeKycLink | null = null
  if (kycLinkId) {
    const result = await getKycLink({ kycLinkId, context, config: input.config, fetchImpl: input.fetchImpl })
    kycLink = result.data
  }

  // The KYC link is what first reveals the customer id, so prefer the stored
  // id but fall back to the one Bridge just returned.
  const customerId = customerIdFromInput || String(kycLink?.customer_id || "").trim()

  let customer: BridgeCustomer | null = null
  if (customerId) {
    const result = await getCustomer({ customerId, context, config: input.config, fetchImpl: input.fetchImpl })
    customer = result.data
  }

  return { connection: normalizeBridgeConnection({ customer, kycLink }), correlationId }
}

/**
 * Read the merchant's normalized Bridge state. Named to match the universal
 * provider-connector contract; `syncCustomerStatus` is the Bridge-native name
 * for the same read.
 */
export async function getMerchantStatus(input: {
  customerId?: string | null
  kycLinkId?: string | null
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}): Promise<NormalizedBridgeConnection> {
  const { connection } = await syncCustomerStatus(input)
  return connection
}

/**
 * Register a webhook endpoint with Bridge.
 *
 * PineTree does NOT provision webhooks automatically during onboarding: the
 * endpoint is a per-developer-account setting, not a per-merchant one, and
 * creating it from request paths would race across deployments. This helper
 * exists for one-time operator setup, and the Bridge Dashboard procedure is
 * documented in docs/environment/bridge-env-checklist.md.
 */
export async function createWebhook(input: {
  url: string
  idempotencyKey: string
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}): Promise<BridgeRequestResult<BridgeWebhookEndpoint>> {
  const result = await bridgeRequest<BridgeWebhookEndpoint>({
    operation: "create_webhook",
    method: "POST",
    path: "/webhooks",
    body: { url: input.url },
    idempotencyKey: input.idempotencyKey,
    context: input.context,
    config: input.config,
    fetchImpl: input.fetchImpl,
  })

  assertIdentifiedObject(result.data, "create_webhook", { correlationId: result.correlationId })
  return result
}

/**
 * Fetch a webhook endpoint's details, including the per-endpoint public key
 * used to verify `X-Webhook-Signature`.
 *
 * The returned key is verification material: it is used to configure
 * BRIDGE_WEBHOOK_PUBLIC_KEY and is never persisted to a database row or
 * returned to a browser.
 */
export async function fetchWebhookDetails(input: {
  webhookId: string
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
}): Promise<BridgeRequestResult<BridgeWebhookEndpoint>> {
  return bridgeRequest<BridgeWebhookEndpoint>({
    operation: "fetch_webhook_details",
    method: "GET",
    path: `/webhooks/${pathSegment(input.webhookId, "fetch_webhook_details")}`,
    context: input.context,
    config: input.config,
    fetchImpl: input.fetchImpl,
  })
}
