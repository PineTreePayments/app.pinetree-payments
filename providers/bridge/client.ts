/**
 * Default request timeout. Bridge publishes no required timeout, so this is a
 * PineTree-chosen value for a control-plane (non-payment) call and is flagged
 * as such rather than presented as an official Bridge figure.
 */
export const BRIDGE_DEFAULT_TIMEOUT_MS = 20_000

function readPositiveIntEnv(name: string, fallback: number): number {
  const raw = String(process.env[name] || "").trim()
  if (!raw) return fallback
  const parsed = Number.parseInt(raw, 10)
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback
}

export function bridgeTimeoutMs(): number {
  return readPositiveIntEnv("BRIDGE_TIMEOUT_MS", BRIDGE_DEFAULT_TIMEOUT_MS)
}

/** PineTree context threaded through every request for correlation and logging. */
export type BridgeRequestContext = {
  correlationId?: string
  merchantId?: string | null
  merchantProviderConnectionId?: string | null
}

export type BridgeRequestOptions = {
  operation: string
  method: "GET" | "POST" | "PUT" | "DELETE"
  path: string
  body?: unknown
  /** Required for every mutating request. Generated by PineTree, never a client value. */
  idempotencyKey?: string
  context?: BridgeRequestContext
  config?: BridgeConfig
  fetchImpl?: typeof fetch
  timeoutMs?: number
}

export type BridgeRequestResult<T> = {
  data: T
  httpStatus: number
  correlationId: string
  /** Bridge's request identifier when the response carries one. */
  providerRequestId: string | null
  elapsedMs: number
}

const MUTATING_METHODS = new Set(["POST", "PUT", "DELETE"])

/**
 * True when a value contains a character that cannot safely appear in an HTTP
 * header: any control character (which includes CR and LF, the header-splitting
 * pair) or DEL.
 */
function hasUnsafeHeaderCharacter(value: string): boolean {
  for (const character of value) {
    const codePoint = character.codePointAt(0) ?? 0
    if (codePoint < 0x20 || codePoint === 0x7f) return true
  }
  return false
}

export function assertUsableIdempotencyKey(key: string, operation: string): void {
  const normalized = String(key || "").trim()
  if (!normalized) {
    throw new BridgeApiError(`Bridge ${operation} requires a PineTree-generated idempotency key.`, {
      httpStatus: 400,
      code: "idempotency_key_required",
      diagnostics: { operation },
    })
  }
  if (normalized.length > 255 || hasUnsafeHeaderCharacter(normalized)) {
    throw new BridgeApiError(`Bridge ${operation} idempotency key is not a usable header value.`, {
      httpStatus: 400,
      code: "idempotency_key_invalid",
      diagnostics: { operation },
    })
  }
}

export function buildBridgeHeaders(input: {
  config: BridgeConfig
  idempotencyKey?: string
  hasBody: boolean
}): Record<string, string> {
  const headers: Record<string, string> = {
    // Bridge's documented authentication header. Exact casing per the docs.
    "Api-Key": input.config.apiKey,
    Accept: "application/json",
  }
  if (input.hasBody) headers["Content-Type"] = "application/json"
  if (input.idempotencyKey) headers["Idempotency-Key"] = input.idempotencyKey
  return headers
}

/** Bridge's correlation identifier, when present under any documented name. */
function extractProviderRequestId(response: Response): string | null {
  for (const name of ["x-request-id", "request-id", "x-bridge-request-id", "cf-ray"]) {
    const value = response.headers.get(name)
    if (value) return value
  }
  return null
}

function extractBridgeErrorCode(body: unknown): string | null {
  if (!body || typeof body !== "object") return null
  const record = body as Record<string, unknown>
  const code = record.code ?? (record.error as Record<string, unknown> | undefined)?.code
  const value = String(code ?? "").trim()
  return value || null
}

/**
 * Execute one Bridge REST request.
 *
 * Throws:
 *   BridgeTransportError       - no usable response (timeout / network)
 *   BridgeInvalidResponseError - 2xx body that is not usable JSON
 *   BridgeApiError             - configuration error or non-2xx provider response
 */
export async function bridgeRequest<T>(options: BridgeRequestOptions): Promise<BridgeRequestResult<T>> {
  const config = options.config ?? getBridgeConfig()
  const context = options.context ?? {}
  const correlationId = context.correlationId || randomUUID()
  const fetchImpl = options.fetchImpl ?? fetch
  const timeoutMs = options.timeoutMs ?? bridgeTimeoutMs()
  const hasBody = options.body !== undefined && MUTATING_METHODS.has(options.method)

  if (MUTATING_METHODS.has(options.method)) {
    assertUsableIdempotencyKey(options.idempotencyKey || "", options.operation)
  }

  const headers = buildBridgeHeaders({
    config,
    idempotencyKey: MUTATING_METHODS.has(options.method) ? options.idempotencyKey : undefined,
    hasBody,
  })

  const diagnostics: BridgeErrorDiagnostics = {
    operation: options.operation,
    correlationId,
    merchantId: context.merchantId ?? null,
    merchantProviderConnectionId: context.merchantProviderConnectionId ?? null,
    idempotencyKeyPresent: Boolean(options.idempotencyKey),
  }

  const url = `${config.baseUrl}${options.path}`
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), timeoutMs)
  const startedAt = Date.now()

  let response: Response
  try {
    response = await fetchImpl(url, {
      method: options.method,
      headers,
      body: hasBody ? JSON.stringify(options.body) : undefined,
      signal: controller.signal,
    })
  } catch {
    const timedOut = controller.signal.aborted
    const elapsedMs = Date.now() - startedAt
    // A timeout after dispatch leaves the outcome UNKNOWN: Bridge may already
    // have created the customer. It is never a proven failure, and it must
    // never be resolved by resending with a fresh idempotency key.
    console.warn("[bridge] transport_failure", {
      ...diagnostics,
      timedOut,
      elapsedMs,
      outcomeClassification: timedOut ? "unknown_requires_state_reread" : "transport_failure",
    })
    throw new BridgeTransportError(
      timedOut ? "Bridge request timed out." : "Bridge is temporarily unreachable.",
      {
        timedOut,
        // A pre-dispatch connection failure did not reach Bridge, but for a
        // mutating operation PineTree cannot prove that, so uncertainty is
        // retained for those.
        outcomeUncertain: timedOut || MUTATING_METHODS.has(options.method),
        diagnostics: { ...diagnostics, elapsedMs },
      }
    )
  } finally {
    clearTimeout(timer)
  }

  const rawText = await response.text().catch(() => "")
  const elapsedMs = Date.now() - startedAt
  const providerRequestId = extractProviderRequestId(response)

  let parsed: unknown = null
  let jsonParsed = false
  if (rawText.trim()) {
    try {
      parsed = JSON.parse(rawText) as unknown
      jsonParsed = true
    } catch {
      jsonParsed = false
    }
  }

  if (!response.ok) {
    const summary = bridgeSafeBodySummary(rawText)
    console.warn("[bridge] api_error", {
      ...diagnostics,
      httpStatus: response.status,
      elapsedMs,
      providerRequestId,
      responseSummary: summary,
    })
    throw new BridgeApiError("Bridge rejected the request.", {
      httpStatus: response.status,
      code: extractBridgeErrorCode(parsed),
      diagnostics: {
        ...diagnostics,
        httpStatus: response.status,
        elapsedMs,
        providerRequestId,
        responseSummary: summary,
      },
    })
  }

  if (!jsonParsed || !parsed || typeof parsed !== "object") {
    const summary = bridgeSafeBodySummary(rawText)
    console.warn("[bridge] invalid_response", {
      ...diagnostics,
      httpStatus: response.status,
      elapsedMs,
      providerRequestId,
      outcomeClassification: "unknown_requires_state_reread",
      responseSummary: summary,
    })
    throw new BridgeInvalidResponseError("Bridge returned a response PineTree could not parse.", {
      ...diagnostics,
      httpStatus: response.status,
      elapsedMs,
      providerRequestId,
      responseSummary: summary,
    })
  }

  console.info("[bridge] operation_result", {
    ...diagnostics,
    httpStatus: response.status,
    elapsedMs,
    providerRequestId,
  })

  return {
    data: parsed as T,
    httpStatus: response.status,
    correlationId,
    providerRequestId,
    elapsedMs,
  }
}

function assertIdentifiedObject(
  value: unknown,
  operation: string,
  diagnostics: BridgeErrorDiagnostics
): void {
  const id = String((value as { id?: unknown } | null)?.id ?? "").trim()
  if (!id) {
    // A 2xx body with no id cannot be trusted as success for an operation whose
    // whole purpose is to yield a durable Bridge identifier.
    console.warn("[bridge] missing_identifier", {
      ...diagnostics,
      operation,
      responseSummary: bridgeSafeBodySummary(JSON.stringify(redactBridgePayload(value))),
    })
    throw new BridgeInvalidResponseError(`Bridge ${operation} response did not include an id.`, {
      ...diagnostics,
      operation,
    })
  }
}

/** URL-path segment escaping so a provider identifier can never alter the path. */
function pathSegment(value: string, operation: string): string {
  const normalized = String(value || "").trim()
  if (!normalized) {
    throw new BridgeApiError(`Bridge ${operation} requires an identifier.`, {
      httpStatus: 400,
      code: "identifier_required",
      diagnostics: { operation },
    })
  }
  return encodeURIComponent(normalized)
}

